package day19;
//dictionary order
//lexicographic order
//ascii value arrangement order
public class Str_compare_to {
	public static void main(String[] args) {
		String s1="madam";
		String s2="maddy";
		if(s1.compareTo(s2)>0) {
			System.out.println(s2);
		System.out.println(s1);
		}
		else
		{
			System.out.println(s1);
			System.out.println(s2);
		}
	}

}
